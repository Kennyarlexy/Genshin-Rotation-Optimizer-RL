    # This is the most critical test for this data structure
    q = FastDeque(capacity=3)
    q.push_back('a')
    q.push_back('b')
    q.push_back('c') # Full: ['a', 'b', 'c']
    
    # Pop from front to move head forward
    assert q.pop_front() == 'a' # Internal array might look like [None, 'b', 'c'] (head at 1)
    
    # Push back to trigger tail wrap-around
    q.push_back('d') 
    # Logical: ['b', 'c', 'd']. Physical array likely ['d', 'b', 'c']
    
    assert str(q) == "['b', 'c', 'd']"
    assert q[0] == 'b'
    assert q[2] == 'd'
    print("✓ Circular Wrap-Around Passed")

