class FastDeque:
    """
    O(1) for `push_back`, `push_front`, `pop_back`, `pop_front`, and random access with index

    No C++ equivalent for "fast" deque in Python is just sad (we only have O(N) random access with `collections.deque`)
    """
    def __init__(self, capacity: int):
        self.capacity = capacity
        self.data = [0] * self.capacity
        self.size = 0
        self.head = 0  # Pointer to front
        self.tail = self.capacity - 1  # Pointer to back

    def push_back(self, item):
        if self.size == self.capacity:
            raise Exception("capacity exceeded, can't push new item")
        
        self.size += 1
        self.tail += 1
        if self.tail == self.capacity:
            self.tail = 0
        self.data[self.tail] = item

    def pop_back(self):
        if self.size == 0:
            raise Exception("empty data, can't pop")
        
        item = self.data[self.tail]

        self.size -= 1
        self.tail -= 1
        if self.tail == -1:
            self.tail = self.capacity - 1
        
        return item
        
    def push_front(self, item):
        if self.size == self.capacity:
            raise Exception("capacity exceeded, can't push new item")
        
        self.size += 1
        self.head -= 1
        if self.head < 0:
            self.head = self.capacity - 1
        self.data[self.head] = item

    def pop_front(self):
        if self.size == 0:
            raise Exception("empty data, can't pop")
        
        item = self.data[self.head]
        
        self.size -= 1
        self.head += 1
        if self.head == self.capacity:
            self.head = 0

        return item

    def __getitem__(self, i):
        if i < 0:
            i += self.size # Handle negative indices like q[-1]
            
        if i >= self.size or i < 0:
            raise IndexError("index out of range")

        i = (self.head + i) % self.capacity
        return self.data[i]

    def __repr__(self):
        return str([self[i] for i in range(self.size)])

